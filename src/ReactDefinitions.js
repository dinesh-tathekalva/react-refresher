// React: is a Js library for building component based and declarative UI.

// Declarative as in, instead of telling browser how to update the DOM, 
// we just define what the DOM should look like based on the state and React handles the updates

// Component based as in, small reusable functions that manage their state and logic. 

// Virtual DOM: React uses an in-memory DOM representation and keeps comparing it with the actual DOM with a process called
// diffing and updates only those elements on DOM which are updated which improves the performance of the App.

// Functional Componenents: They are nothing but simple JS functions which accepts props as inputs, returns JSX to render UI and we can use
// hooks like useState and useEffect to manage state and lifecycle s

// JSX: JSX is a syntax extension to write UI in JS

